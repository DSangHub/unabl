import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {parse as js} from 'acorn';
import {parseFragment as html} from 'parse5';

const phrases=new Set(['Language','Translating…','Some translations are temporarily unavailable. English is shown where needed.']);
const attrs=new Set(['placeholder','title','aria-label','alt']);
function add(value) {
 const text=value?.trim().replace(/\s+/g,' ');
 if(text && text.length<=1800 && /[A-Za-z]{2}/.test(text) && !/^(https?:|mailto:|data:|#[\w-]+$|[a-z0-9_./-]+\.(js|html)$)/i.test(text)) phrases.add(text);
}
function markup(value){
 function walk(node){
  if(['style','script','svg','code'].includes(node.tagName))return;
  if(node.nodeName==='#text')add(node.value);
  for(const a of node.attrs||[])if(attrs.has(a.name))add(a.value);
  for(const child of node.childNodes||[])walk(child);
 }
 walk(html(value));
}
function script(code,sourceType='module'){
 function walk(node){
  if(!node||typeof node!=='object')return;
  if(node.type==='Literal'&&typeof node.value==='string')handle(node.value);
  if(node.type==='TemplateLiteral') {
   const parts=node.quasis.map(q=>q.value.cooked||'');
   if(parts.some(p=>/<[a-z][\w-]*[\s>]/i.test(p)))markup(parts.join(''));
   else for(const p of parts)add(p);
  }
  for(const val of Object.values(node))if(Array.isArray(val))val.forEach(walk);else if(val&&typeof val==='object')walk(val);
 }
 walk(js(code,{ecmaVersion:'latest',sourceType}));
}
function handle(value){
 if(/<[a-z][\w-]*[\s>]/i.test(value))markup(value);else add(value);
}
function page(value){
 markup(value.replace(/<head[\s>][\s\S]*?<\/head>/i,''));
 add(value.match(/<title>([^<]+)<\/title>/i)?.[1]);
 for(const [,body] of value.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi))script(body,'script');
}
for(const path of ['welcome.js','index.html','card-editor.html',...readdirSync('.').filter(f=>f.endsWith('.js')&&!['welcome.js','site-language.js','site-locales.js','site-catalog.js'].includes(f)),...['api','lib'].flatMap(d=>readdirSync(d).filter(f=>f.endsWith('.js')&&f!=='site-language.js'&&f!=='site-translation.js').map(f=>d+'/'+f))]){
 const source=readFileSync(path,'utf8');
 if(path.endsWith('.html')){
  page(source);
  const embedded=source.match(/const ecardSource='([A-Za-z0-9+/=]+)'/);
  if(embedded)page(Buffer.from(embedded[1],'base64').toString('utf8'));
 }else script(source);
}
// Skip internal tokens, selectors and identifiers that cannot be UI copy.
const list=[...phrases].filter(s=>!/^[a-z][a-z0-9_.:/-]*$/.test(s)||['yes','no','optional','required'].includes(s));
const parts=[];let size=0;
for(const s of list){
 if(!parts.length||size+s.length>4200||parts.at(-1).length>=65){parts.push([]);size=0;}
 parts.at(-1).push(s);size+=s.length;
}
const version=createHash('sha256').update(JSON.stringify(parts)).digest('hex').slice(0,12);
writeFileSync('site-catalog.js','// Generated by npm run build:languages.\nexport const version='+JSON.stringify(version)+';\nexport const parts='+JSON.stringify(parts)+';\n');
console.log(list.length+' phrases in '+parts.length+' translation groups');
